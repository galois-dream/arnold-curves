"""Codimension aN - b of Arnold's curve classes, checked against his superscripts.

Written 2026-10-15 14:45 CEST.  [Ours] reading of [Arnold] p. 33:
  A_f = f^* m  (subalgebra of C[[t]] generated by the components f_i, no constant),
  a   = dim M^1 / A_f                                   (M^1 = t C[[t]]),
  b   = dim (M^1 f' + A_f^N) / A_f^N,
  codim of the class in C^N = a N - b.
All series are truncated mod t^K; this is exact once t^K C[[t]] lies in A_f (K above the conductor).
Run: .venv/bin/python computations/codim_check.py
"""
from fractions import Fraction

K = 48  # truncation order; asserted below to exceed conductor + leading exponents


def mul(u, v):
    """Product of two truncated series (lists of length K, index = exponent)."""
    w = [Fraction(0)] * K
    for i, x in enumerate(u):
        if x:
            for j, y in enumerate(v[: K - i]):
                if y:
                    w[i + j] += x * y
    return w


class Span:
    """Row-echelon basis of a subspace of Q^n (exact arithmetic)."""

    def __init__(self):
        self.rows = {}  # pivot index -> row with 1 at pivot

    def reduce(self, v):
        v = list(v)
        for p, r in self.rows.items():
            if v[p]:
                c = v[p]
                v = [x - c * y for x, y in zip(v, r)]
        return v

    def add(self, v):
        v = self.reduce(v)
        p = next((i for i, x in enumerate(v) if x), None)
        if p is None:
            return False
        c = v[p]
        v = [x / c for x in v]
        for q, r in self.rows.items():  # keep fully reduced
            if r[p]:
                self.rows[q] = [x - r[p] * y for x, y in zip(r, v)]
        self.rows[p] = v
        return True


def series(comp):
    """comp: int a -> t^a ; tuple (a, b, ...) -> t^a + t^b + ... ; dict {exp: coeff}."""
    v = [Fraction(0)] * K
    terms = {comp: 1} if isinstance(comp, int) else (comp if isinstance(comp, dict) else {e: 1 for e in comp})
    for e, c in terms.items():
        v[e] += Fraction(c)
    return v


def local_algebra(fs):
    """Span of A_f = f^* m mod t^K: close span{f_i} under multiplication by the f_i."""
    A, frontier = Span(), list(fs)
    while frontier:
        new = [v for v in frontier if A.add(v)]
        frontier = [mul(v, f) for v in new for f in fs]
    return A


def a_b(curve):
    fs = [series(c) for c in curve]
    N = len(fs)
    A = local_algebra(fs)
    gaps = [m for m in range(1, K) if m not in A.rows]
    lead = max(min(i for i, x in enumerate(f) if x) for f in fs)
    assert max(gaps) + lead + 2 < K, "raise K"
    a = len(gaps)
    # A_f^N inside (M^1/M^K)^N, as vectors of length N*K
    big = Span()
    for i in range(N):
        for r in A.rows.values():
            v = [Fraction(0)] * (N * K)
            v[i * K:(i + 1) * K] = r
            big.add(v)
    base = len(big.rows)
    dfs = [[m * f[m] if m < K else 0 for m in range(1, K)] + [Fraction(0)] for f in fs]  # f' (index = exponent)
    for k in range(1, K):  # t^k f'
        tk = [Fraction(0)] * K
        tk[k] = Fraction(1)
        big.add([x for d in dfs for x in mul(tk, d)])
    return a, len(big.rows) - base, max(gaps) + 1


# [Arnold] symbol -> (a, b) read off his superscript aN - b.  Pages: Thm 3 p.30; E-hierarchy p.31;
# Thm 5 p.31 (series at their first index).  Binomial (p, q) means t^p + t^q.
CASES = [
    ("(2,3)", [2, 3], (1, 0), "p.30 Thm 3"),
    ("(3,4,5)", [3, 4, 5], (2, 0), "p.31"),
    ("(3,4)", [3, 4], (3, 2), "p.31"),
    ("(3,5,7)", [3, 5, 7], (3, 1), "p.31"),
    ("(3,5)", [3, 5], (4, 3), "p.31"),
    ("(3,7,8)", [3, 7, 8], (4, 2), "p.31"),
    ("(3,(7,8),11)", [3, (7, 8), 11], (5, 4), "p.31"),
    ("(3,8,10)", [3, 8, 10], (5, 3), "p.31"),
    ("(3,7,11)", [3, 7, 11], (5, 3), "p.31"),
    ("a_3=(4,(6,7))", [4, (6, 7)], (8, 9), "p.31 Thm 5"),
    ("b_2=(4,(6,7),15)", [4, (6, 7), 15], (7, 7), "p.31 Thm 5"),
    ("c_1=(4,(6,7),11)", [4, (6, 7), 11], (6, 5), "p.31 Thm 5"),
    ("d_0=(4,(6,7),9,11)", [4, (6, 7), 9, 11], (5, 3), "p.31 Thm 5"),
    ("e_-1=(4,(6,7),9)", [4, (6, 7), 9], (4, 1), "p.31 Thm 5"),
    ("f_1=(4,6,7,9)", [4, 6, 7, 9], (6, 6), "p.31 Thm 5"),
    ("g_0=(4,6,7)", [4, 6, 7], (5, 4), "p.31 Thm 5"),
]

# [Ours] As printed, e_k = (4,(6,2k+9),2k+11)^{(5+k)N-(2+k)} and f_k = (4,6,2k+5,2k+7)^{(5+k)N-(5+k)}
# both disagree with the p.33 formula; moving the binomial bracket from e_k to f_k makes both agree.
SWAPPED = [
    ("e_k as printed", lambda k: [4, (6, 2 * k + 9), 2 * k + 11], lambda k: (5 + k, 2 + k), -1),
    ("f_k as printed", lambda k: [4, 6, 2 * k + 5, 2 * k + 7], lambda k: (5 + k, 5 + k), 1),
    ("e_k = (4,6,2k+9,2k+11)", lambda k: [4, 6, 2 * k + 9, 2 * k + 11], lambda k: (5 + k, 2 + k), -1),
    ("f_k = (4,(6,2k+5),2k+7)", lambda k: [4, (6, 2 * k + 5), 2 * k + 7], lambda k: (5 + k, 5 + k), 1),
]

if __name__ == "__main__":
    print(f"{'class':22} {'computed':>10} {'Arnold':>10}  conductor  source")
    for name, curve, (ea, eb), src in CASES:
        a, b, c = a_b(curve)
        print(f"{name:22} {f'{a}N-{b}':>10} {f'{ea}N-{eb}':>10}  {c:9d}  {src}"
              + ("" if (a, b) == (ea, eb) else "   <-- MISMATCH"))
    print("\nSeries e_k, f_k over four indices (computed vs Arnold's superscript):")
    for name, curve, expect, k0 in SWAPPED:
        res = [(k, a_b(curve(k))[:2], expect(k)) for k in range(k0, k0 + 4)]
        good = all(got == exp for _, got, exp in res)
        print(f"  {name:26} {'agree' if good else 'DISAGREE'}: "
              + ", ".join(f"k={k}:{g[0]}N-{g[1]}" for k, g, _ in res))
